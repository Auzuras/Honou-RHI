#ifndef HONOU_RENDER_IMAGE_H
#define HONOU_RENDER_IMAGE_H

#include <cstdint>

enum class TextureFormat : uint32_t
{
	HONOU_FORMAT_UNDEFINED				=	0,

	HONOU_FORMAT_R8G8B8A8_UNORM			=	1,
	HONOU_FORMAT_B8G8R8A8_UNORM			=	2,
	HONOU_FORMAT_R8G8B8_UNORM			=	3,
	HONOU_FORMAT_B8G8R8_UNORM			=	4,

	HONOU_FORMAT_R8G8B8A8_SRGB			=	5,
	HONOU_FORMAT_B8G8R8A8_SRGB			=	6,
	HONOU_FORMAT_R8G8B8_SRGB			=	7,
	HONOU_FORMAT_B8G8R8_SRGB			=	8,

	HONOU_FORMAT_R16G16B16A16_FLOAT		=	9,
	HONOU_FORMAT_R32G32B32A32_FLOAT		=	10,

	HOUNOU_FORMAT_D32_FLOAT				=	11,
	HOUNOU_FORMAT_D32_FLOAT_S8_UINT		=	12,
	HOUNOU_FORMAT_D24_UNORM_S8_UINT		=	13
};

struct ImageDescription
{
	uint32_t width = 0;
	uint32_t height = 0;
	TextureFormat format = TextureFormat::HONOU_FORMAT_R8G8B8A8_UNORM;
};

#endif //HONOU_RENDER_SURFACE_H